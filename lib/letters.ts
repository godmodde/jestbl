const K = 0.5523;
function oval(cx: number, cy: number, rx: number, ry: number): Stroke {
  const [kx, ky] = [K * rx, K * ry];
  return `M${cx} ${cy - ry} C${cx - kx} ${cy - ry} ${cx - rx} ${cy - ky} ${cx - rx} ${cy} C${cx - rx} ${cy + ky} ${cx - kx} ${cy + ry} ${cx} ${cy + ry} C${cx + kx} ${cy + ry} ${cx + rx} ${cy + ky} ${cx + rx} ${cy} C${cx + rx} ${cy - ky} ${cx + kx} ${cy - ry} ${cx} ${cy - ry}`;
}

