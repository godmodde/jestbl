/** Точки вдоль пути через равные промежутки ≈ step (первая и последняя — концы черты). Без DOM: работает в тестах и на сервере. */
export function sampleStroke(d: string, step = 2): Point[] {
  // Сначала ломаная: кривые дробим мелко, потом идём по ней с шагом step.
  const tokens = d.match(/[MLQC]|-?\d*\.?\d+/g) ?? [];
  const line: Point[] = [];
  let cmd = "";
  for (let t = 0; t < tokens.length; ) {
    if (/[MLQC]/.test(tokens[t])) cmd = tokens[t++];
    const n = { M: 2, L: 2, Q: 4, C: 6 }[cmd as "M"] ?? 0;
    if (!n) throw new Error(`sampleStroke: неизвестная команда в «${d}»`);
    const v = tokens.slice(t, t + n).map(Number);
    t += n;
    const p0 = line[line.length - 1];
    if (cmd === "M" || cmd === "L") { line.push({ x: v[0], y: v[1] }); continue; }
    const pts = [p0, ...Array.from({ length: n / 2 }, (_, k) => ({ x: v[2 * k], y: v[2 * k + 1] }))];
    for (let s = 1; s <= 32; s++) line.push(bezier(pts, s / 32));
  }

  const lens = [0];
  for (let k = 1; k < line.length; k++) lens.push(lens[k - 1] + Math.hypot(line[k].x - line[k - 1].x, line[k].y - line[k - 1].y));
  const total = lens[lens.length - 1];
  const count = Math.max(1, Math.round(total / step));
  const out: Point[] = [];
  for (let s = 0, k = 1; s <= count; s++) {
    const at = (total * s) / count;
    while (k < line.length - 1 && lens[k] < at) k++;
    const span = lens[k] - lens[k - 1] || 1;
    const f = Math.min(1, Math.max(0, (at - lens[k - 1]) / span));
    out.push({ x: line[k - 1].x + (line[k].x - line[k - 1].x) * f, y: line[k - 1].y + (line[k].y - line[k - 1].y) * f });
  }
  return out;
}

/** Где рисовать номер черты и стрелку направления (общая разметка для обводилки и проверочного листа). */
export function strokeMarks(strokes: Stroke[]) {
  const badges: Point[] = [];
  return strokes.map((d) => {
    const p = sampleStroke(d, 1);
    const last = p.length - 1;
    const [start, ahead] = [p[0], p[Math.min(last, 3)]];
    const len = Math.hypot(ahead.x - start.x, ahead.y - start.y) || 1;
    const dot = last < 8;
    const k = Math.round(Math.min(last / 2, 24));
    // Номер — чуть до начала, против хода черты, чтобы не закрывать линию. У точки (Ё) номер — на ней самой.
    let badge = dot ? p[k] : {
      x: Math.min(95, Math.max(5, start.x - ((ahead.x - start.x) / len) * 8)),
      y: Math.min(135, Math.max(5, start.y - ((ahead.y - start.y) / len) * 8)),
    };
    // Две черты из одной точки (А, М) — второй номер ставим на саму черту.
    if (!dot && badges.some((b) => Math.hypot(b.x - badge.x, b.y - badge.y) < 10)) badge = p[Math.min(last, 14)];
    badges.push(badge);
    const [a, b] = [p[k], p[Math.min(last, k + 2)]];
    const arrow = dot ? null : { x: a.x, y: a.y, angle: (Math.atan2(b.y - a.y, b.x - a.x) * 180) / Math.PI };
    return { start, badge, arrow };
  });
}

// Де Кастельжо: одна формула для квадратичной и кубической кривой.
function bezier(pts: Point[], t: number): Point {
  while (pts.length > 1) pts = pts.slice(1).map((p, k) => ({ x: pts[k].x + (p.x - pts[k].x) * t, y: pts[k].y + (p.y - pts[k].y) * t }));
  return pts[0];
}
