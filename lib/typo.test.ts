import { expect, it } from "vitest";

import { nbsp } from "./typo";

it("привязывает короткие слова к следующему", () => {
  const out = nbsp("Короткие уроки без перегруза и лишней теории. Подходит и для знакомых");
  expect(out).toBe("Короткие уроки без перегруза и лишней теории. Подходит и для знакомых");
  expect(nbsp("Начните с первого жеста.")).toBe("Начните с первого жеста.");
  expect(nbsp("Смотрите")).toBe("Смотрите");
});
